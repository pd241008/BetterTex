// fetchCtanArchive downloads the archive for pkg, verifies SHA-256 when known,
// and extracts member files into cacheDir (Tier 3). Network failures return a
// wrapped error; tests inject ctanFetch instead of calling this.
func fetchCtanArchive(pkg string, cacheDir string) error {
	entry, ok := EmbeddedCtanIndex().Lookup(pkg)
	if !ok {
		return fmt.Errorf("package %q absent from CTAN inverted index", pkg)
	}

	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Get(entry.Tarball)
	if err != nil {
		return fmt.Errorf("download %s: %w", entry.Tarball, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("download %s: http %d", entry.Tarball, resp.StatusCode)
	}

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return fmt.Errorf("read %s body: %w", pkg, err)
	}
	if entry.SHA256 != "" {
		sum := sha256.Sum256(body)
		if hex.EncodeToString(sum[:]) != entry.SHA256 {
			return fmt.Errorf("sha256 mismatch for %s tarball", pkg)
		}
	}
	return extractArchive(body, cacheDir, pkg)
}

// extractArchive unpacks a gzipped tar (or raw member blobs) into cacheDir.
func extractArchive(body []byte, cacheDir string, pkg string) error {
	if err := os.MkdirAll(cacheDir, 0o755); err != nil {
		return err
	}
	gz, gzErr := gzip.NewReader(strings.NewReader(string(body)))
	if gzErr == nil {
		tr := tar.NewReader(gz)
		for {
			hdr, err := tr.Next()
			if err == io.EOF {
				return nil
			}
			if err != nil {
				return err
			}
			if hdr.Typeflag != tar.TypeReg && hdr.Typeflag != tar.TypeRegA {
				continue
			}
			name := filepath.Base(hdr.Name) // flatten — Tier 3 is a flat package dir
			out, err := os.Create(filepath.Join(cacheDir, name))
			if err != nil {
				return err
			}
			if _, err := io.Copy(out, tr); err != nil {
				out.Close()
				return err
			}
			out.Close()
		}
	}
	// Non-gzip payloads (e.g. zip members) are written verbatim as files.
	return os.WriteFile(filepath.Join(cacheDir, pkg+".zip"), body, 0o644)
}
