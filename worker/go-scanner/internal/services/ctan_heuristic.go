// Package services — ctan_heuristic.go: the Tier-4 heuristic resolver.
// Holds an embedded inverted index mapping individual .sty/.cls filenames to
// their parent CTAN archive (e.g. algpseudocode.sty → algorithmicx), plus the
// concurrent download + SHA-256 verification + extraction into Tier 3.
package services

import (
	"archive/tar"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// CtanEntry — one archive in the inverted index.
type CtanEntry struct {
	// Primary archive name, e.g. "algorithmicx".
	ArchiveName string `json:"archive_name"`
	// Members that live inside this archive (aliases), e.g. "algpseudocode".
	Provides []string `json:"provides,omitempty"`
	// Tarball URL of the archive.
	Tarball string `json:"tarball"`
	// Expected SHA-256 of the tarball (hex). Empty = unverified.
	SHA256 string `json:"sha256,omitempty"`
}

// CtanIndex — inverted index: member package → archive entry.
type CtanIndex struct {
	byMember map[string]CtanEntry
}

// Lookup resolves a member (e.g. "algpseudocode") to its parent archive.
func (i CtanIndex) Lookup(member string) (CtanEntry, bool) {
	e, ok := i.byMember[member]
	return e, ok
}

// Len returns the number of indexed members.
func (i CtanIndex) Len() int { return len(i.byMember) }

const ctanContribURL = "https://mirrors.ctan.org/macros/latex/contrib/%s.zip"

