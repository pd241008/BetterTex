// TexCraft CTAN inverted-index generator (Phase 2 contract artifact).
//
// Emits an index (stdout or -o file) mapping individual .sty/.cls filenames to
// their parent CTAN archive (e.g., "algpseudocode.sty" -> "algorithmicx").
// It is refreshed by infra CI so the Go scanner's Tier 4 (ADR-003) can resolve
// packages offline from the embedded index.
//
// Usage: go run ./infra/scripts/generate_ctan_index.go -o ctan_index.json
//
// Phase 2 replaces this stub with the real mirror-walking implementation.
package main

import (
	"flag"
	"fmt"
	"os"
)

func main() {
	out := flag.String("o", "", "output index file (default: stdout)")
	format := flag.String("format", "json", "index format: json")
	flag.Parse()

	w := os.Stdout
	if *out != "" {
		f, err := os.Create(*out)
		if err != nil {
			fmt.Fprintf(os.Stderr, "generate_ctan_index: %v\n", err)
			os.Exit(1)
		}
		defer f.Close()
		w = f
	}
	if *format != "json" {
		fmt.Fprintf(os.Stderr, "generate_ctan_index: unsupported format %q\n", *format)
		os.Exit(1)
	}
	fmt.Fprintln(w, "{")
	fmt.Fprintln(w, "  \"version\": 1,")
	fmt.Fprintln(w, "  \"comment\": \"inverted index .sty/.cls -> CTAN archive; regenerated by Phase 2\"")
	fmt.Fprintln(w, "}")
}
